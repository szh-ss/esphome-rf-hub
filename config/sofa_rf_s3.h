void sofa_init() {
  sofa_spi_begin();
  delay(5);
  // 复刻已验证可用的工作版初始化（参数来自原遥控器 SPI 抓取）
  nrf_writeReg(NREG_CONFIG, 0x08);     // 先断电
  delay(5);
  nrf_writeReg(NREG_SETUP_AW, 0x03);   // 5 字节地址
  nrf_writeReg(NREG_RF_CH, 0x50);      // 2480 MHz
  nrf_writeReg(NREG_RF_SETUP, 0x07);   // 1 Mbps, 0 dBm
  nrf_writeReg(NREG_EN_AA, 0x00);      // 关闭 auto-ack（与工作版一致）
  nrf_writeReg(NREG_EN_RXADDR, 0x01);  // 使能 pipe0
  nrf_writeReg(NREG_FEATURE, 0x05);    // EN_DYN_ACK | EN_DPL（开 DPL）
  nrf_writeReg(NREG_DYNPD, 0x01);      // pipe0 开动态长度
  nrf_writeAddr(NREG_TX_ADDR, 0x000003DC05ULL);   // 05 DC 03 00 00
  nrf_writeAddr(NREG_RX_ADDR_P0, 0x000003DC05ULL);
  nrf_writeReg(NREG_STATUS, 0x70);
  nrf_cs(LOW); sofa_spi_rw(NCMD_FLUSH_TX); nrf_cs(HIGH);
  nrf_writeReg(NREG_CONFIG, 0x0E);     // PWR_UP | PRIM_TX | EN_CRC | CRCO
  delay(5);
}

// name: r1o r1i r2o r2i r3o r3i rao rai
void sofa_send(const char* name) {
  const uint8_t (*d)[8] = nullptr; int len = 0;
  if      (sofa_strcmp(name,"r1o")==0){d=cmd1o;len=cmd1o_len;}
  else if (sofa_strcmp(name,"r1i")==0){d=cmd1i;len=cmd1i_len;}
  else if (sofa_strcmp(name,"r2o")==0){d=cmd2o;len=cmd2o_len;}
  else if (sofa_strcmp(name,"r2i")==0){d=cmd2i;len=cmd2i_len;}
  else if (sofa_strcmp(name,"r3o")==0){d=cmd3o;len=cmd3o_len;}
  else if (sofa_strcmp(name,"r3i")==0){d=cmd3i;len=cmd3i_len;}
  else if (sofa_strcmp(name,"rao")==0){d=cmdao;len=cmdao_len;}
  else if (sofa_strcmp(name,"rai")==0){d=cmdai;len=cmdai_len;}
  else return;
  for (int i=0;i<len;i++){ nrf_sendFrame(d[i],8); delay(20); }
}
