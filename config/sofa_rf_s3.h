// ESPHome 专用：纯 GPIO 软件模拟 SPI，零外部库依赖（不依赖 SPI.h / RF24.h）。
// 数据/初始化/发送全打包进一个 .h，靠 YAML 的 includes: 引入。
// 引脚（ESP32-S3 版，避开风扇灯已占用的 4/5/7/12/13/14）：
//   CE=GPIO15  CSN=GPIO16  SCK=GPIO17  MOSI=GPIO18  MISO=GPIO21
// 软件 SPI 零库依赖，ESP32/ESP8266 通用；改脚位改下面 5 个 #define 即可。

#define SOFA_SCK   17
#define SOFA_MOSI  18
#define SOFA_MISO  21
#define SOFA_CE    15
#define SOFA_CSN   16

// ---- nRF24L01 寄存器 / 命令 ----
#define NREG_CONFIG      0x00
#define NREG_EN_AA       0x01
#define NREG_EN_RXADDR   0x02
#define NREG_SETUP_AW    0x03
#define NREG_RF_CH       0x05
#define NREG_RF_SETUP    0x06
#define NREG_STATUS      0x07
#define NREG_RX_ADDR_P0  0x0A
#define NREG_TX_ADDR     0x10
#define NREG_FIFO_STATUS 0x17
#define NREG_DYNPD       0x1C
#define NREG_FEATURE     0x1D
#define NCMD_WREG        0x20
#define NCMD_FLUSH_TX    0xE1
// 原装遥控器用 W_TX_PAYLOAD_NOACK（免确认包）。原始 SPI 抓包里每帧命令是
// B0，不是 A0；FEATURE 中的 EN_DYN_ACK(bit0) 正是为这条命令开的。
#define NCMD_W_TX_PAYLOAD_NOACK 0xB0
#define NCMD_NOP         0xFF

// ---------- 软件 SPI（GPIO 模拟，CPOL=0/CPHA=0，MSB first）----------
static void sofa_spi_begin() {
  pinMode(SOFA_SCK, OUTPUT);
  pinMode(SOFA_MOSI, OUTPUT);
  pinMode(SOFA_MISO, INPUT);
  pinMode(SOFA_CE, OUTPUT);
  pinMode(SOFA_CSN, OUTPUT);
  digitalWrite(SOFA_CSN, HIGH);
  digitalWrite(SOFA_CE, LOW);
  digitalWrite(SOFA_SCK, LOW);
}
// 写一个字节，同时读回（用于读 STATUS 等）
static uint8_t sofa_spi_rw(uint8_t b) {
  uint8_t r = 0;
  for (int i = 7; i >= 0; i--) {
    digitalWrite(SOFA_SCK, LOW);
    digitalWrite(SOFA_MOSI, (b >> i) & 0x01);
    delayMicroseconds(2);
    digitalWrite(SOFA_SCK, HIGH);
    delayMicroseconds(1);
    r = (r << 1) | (digitalRead(SOFA_MISO) ? 1 : 0);
    delayMicroseconds(1);
  }
  digitalWrite(SOFA_SCK, LOW);
  return r;
}

static void nrf_cs(uint8_t level) { digitalWrite(SOFA_CSN, level); }

static uint8_t nrf_readReg(uint8_t reg) {
  nrf_cs(LOW);
  sofa_spi_rw(reg);
  uint8_t v = sofa_spi_rw(NCMD_NOP);
  nrf_cs(HIGH);
  return v;
}
static void nrf_writeReg(uint8_t reg, uint8_t val) {
  nrf_cs(LOW);
  sofa_spi_rw(NCMD_WREG | reg);
  sofa_spi_rw(val);
  nrf_cs(HIGH);
}
static void nrf_writeAddr(uint8_t reg, uint64_t addr) {
  nrf_cs(LOW);
  sofa_spi_rw(NCMD_WREG | reg);
  for (int i = 0; i < 5; i++) sofa_spi_rw((uint8_t)(addr >> (8 * i)));
  nrf_cs(HIGH);
}
// 完全照抄原装遥控器的一次按键帧序列（24 MHz 逻辑分析仪抓包
// 「电动沙发/sr/1号沙发移出.sr」，每帧 6 个 CSN 事务，共 60 帧）：
//   20 00        写 CONFIG=0x00（掉电）
//   E1           FLUSH_TX
//   B0 <8 bytes> W_TX_PAYLOAD_NOACK，免确认包
//   20 0E        写 CONFIG=0x0E（上电 TX；原装 CE 恒高，靠这次上电触发发送）
//   07 FF        轮询 STATUS
//   27 2E        清 TX_DS
// 原实现有两处偏差：用 A0 普通 payload、用 CE 脉冲触发，且帧间隔 20ms。
static bool nrf_sendFrame(const uint8_t* data, uint8_t len) {
  nrf_writeReg(NREG_CONFIG, 0x00);          // 掉电
  nrf_cs(LOW); sofa_spi_rw(NCMD_FLUSH_TX); nrf_cs(HIGH);
  nrf_cs(LOW);
  sofa_spi_rw(NCMD_W_TX_PAYLOAD_NOACK);
  for (int i = 0; i < len; i++) sofa_spi_rw(data[i]);
  nrf_cs(HIGH);
  nrf_writeReg(NREG_CONFIG, 0x0E);          // 上电即发送（CE 由 sofa_send 置高）
  uint32_t t0 = millis();
  while (millis() - t0 < 50) {              // 空中时间 <1ms，50ms 足够
    if (nrf_readReg(NREG_STATUS) & 0x20) {  // TX_DS
      nrf_writeReg(NREG_STATUS, 0x2E);      // 照抄原装的中断清除值
      return true;
    }
    delay(1);
  }
  return false;
}

// 读回一组寄存器用于自检。SPI 正常时 CONFIG=0x0E、RF_CH=0x50、
// RF_SETUP=0x07、AW=0x03、TX_ADDR 首字节=0x05；全 0x00 / 0xFF 说明
// 模块没接好或供电不足，MISO 恒定电平。
static void nrf_dump(const char* stage) {
  ESP_LOGI("sofa", "[%s] CONFIG=0x%02X CH=0x%02X RF_SETUP=0x%02X AW=0x%02X STATUS=0x%02X FIFO=0x%02X FEATURE=0x%02X ADDR0=0x%02X",
           stage,
           nrf_readReg(NREG_CONFIG), nrf_readReg(NREG_RF_CH),
           nrf_readReg(NREG_RF_SETUP), nrf_readReg(NREG_SETUP_AW),
           nrf_readReg(NREG_STATUS), nrf_readReg(NREG_FIFO_STATUS),
           nrf_readReg(NREG_FEATURE), nrf_readReg(NREG_RX_ADDR_P0));
}

// ---------- 简易字符串比较（避免依赖 <cstring>）----------
static int sofa_strcmp(const char* a, const char* b) {
  while (*a && (*a == *b)) { a++; b++; }
  return (int)(unsigned char)*a - (int)(unsigned char)*b;
}

