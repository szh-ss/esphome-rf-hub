// ESPHome 专用：纯 GPIO 软件模拟 SPI，零外部库依赖（不依赖 SPI.h / RF24.h）。
// 数据/初始化/发送全打包进一个 .h，靠 YAML 的 includes: 引入。
// 引脚（ESP32-S3 版，避开风扇灯已占用的 4/5/7/12/13/14）：
//   CE=GPIO15  CSN=GPIO16  SCK=GPIO17  MOSI=GPIO18  MISO=GPIO21
// 软件 SPI 零库依赖，ESP32/ESP8266 通用；改脚位改下面 5 个 #define 即可。

#define SOFA_SCK   17
#define SOFA_MOSI  18
#define SOFA_MISO  21
#define SOFA_CE    15
#define SOFA_CSN   16

// ---- nRF24L01 寄存器 / 命令 ----
#define NREG_CONFIG      0x00
#define NREG_EN_AA       0x01
#define NREG_EN_RXADDR   0x02
#define NREG_SETUP_AW    0x03
#define NREG_RF_CH       0x05
#define NREG_RF_SETUP    0x06
#define NREG_STATUS      0x07
#define NREG_RX_ADDR_P0  0x0A
#define NREG_TX_ADDR     0x10
#define NREG_FIFO_STATUS 0x17
#define NREG_DYNPD       0x1C
#define NREG_FEATURE     0x1D
#define NCMD_WREG        0x20
#define NCMD_FLUSH_TX    0xE1
#define NCMD_W_TX_PAYLOAD 0xA0
#define NCMD_NOP         0xFF

// ---------- 软件 SPI（GPIO 模拟，CPOL=0/CPHA=0，MSB first）----------
static void sofa_spi_begin() {
  pinMode(SOFA_SCK, OUTPUT);
  pinMode(SOFA_MOSI, OUTPUT);
  pinMode(SOFA_MISO, INPUT);
  pinMode(SOFA_CE, OUTPUT);
  pinMode(SOFA_CSN, OUTPUT);
  digitalWrite(SOFA_CSN, HIGH);
  digitalWrite(SOFA_CE, LOW);
  digitalWrite(SOFA_SCK, LOW);
}
// 写一个字节，同时读回（用于读 STATUS 等）
static uint8_t sofa_spi_rw(uint8_t b) {
  uint8_t r = 0;
  for (int i = 7; i >= 0; i--) {
    digitalWrite(SOFA_SCK, LOW);
    digitalWrite(SOFA_MOSI, (b >> i) & 0x01);
    delayMicroseconds(2);
    digitalWrite(SOFA_SCK, HIGH);
    delayMicroseconds(1);
    r = (r << 1) | (digitalRead(SOFA_MISO) ? 1 : 0);
    delayMicroseconds(1);
  }
  digitalWrite(SOFA_SCK, LOW);
  return r;
}

static void nrf_cs(uint8_t level) { digitalWrite(SOFA_CSN, level); }

static uint8_t nrf_readReg(uint8_t reg) {
  nrf_cs(LOW);
  sofa_spi_rw(reg);
  uint8_t v = sofa_spi_rw(NCMD_NOP);
  nrf_cs(HIGH);
  return v;
}
static void nrf_writeReg(uint8_t reg, uint8_t val) {
  nrf_cs(LOW);
  sofa_spi_rw(NCMD_WREG | reg);
  sofa_spi_rw(val);
  nrf_cs(HIGH);
}
static void nrf_writeAddr(uint8_t reg, uint64_t addr) {
  nrf_cs(LOW);
  sofa_spi_rw(NCMD_WREG | reg);
  for (int i = 0; i < 5; i++) sofa_spi_rw((uint8_t)(addr >> (8 * i)));
  nrf_cs(HIGH);
}
static void nrf_sendFrame(const uint8_t* data, uint8_t len) {
  nrf_writeReg(NREG_STATUS, 0x70);          // 清 TX_DS / MAX_RT
  nrf_cs(LOW); sofa_spi_rw(NCMD_FLUSH_TX); nrf_cs(HIGH);
  nrf_cs(LOW);
  sofa_spi_rw(NCMD_W_TX_PAYLOAD);
  for (int i = 0; i < len; i++) sofa_spi_rw(data[i]);
  nrf_cs(HIGH);
  digitalWrite(SOFA_CE, HIGH);              // CE 脉冲 >10us 触发发送
  delayMicroseconds(20);
  digitalWrite(SOFA_CE, LOW);
  uint32_t t0 = millis();
  while (millis() - t0 < 1000) {
    if (nrf_readReg(NREG_STATUS) & 0x20) {  // 等待 TX_DS
      nrf_writeReg(NREG_STATUS, 0x20);
      break;
    }
    delay(1);
  }
}

// ---------- 简易字符串比较（避免依赖 <cstring>）----------
static int sofa_strcmp(const char* a, const char* b) {
  while (*a && (*a == *b)) { a++; b++; }
  return (int)(unsigned char)*a - (int)(unsigned char)*b;
}

