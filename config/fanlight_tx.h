// 整组码表转 vector，供 remote_transmitter.transmit_raw 的 code lambda 使用
inline std::vector<int32_t> code(Key key) {
  const int32_t *p = CODES[key];
  return std::vector<int32_t>(p, p + 66);
}

// HA 风扇卡片上报的是 1~6 挡（speed_level），映射成对应那组独立发射码。
// 六挡之间数值互不递增，不是同一个码带参数，只能逐挡取表；越界钳制到首尾。
inline Key speed_key(int speed) {
  if (speed < 1) speed = 1;
  if (speed > 6) speed = 6;
  return static_cast<Key>(SPEED_1 + speed - 1);
}

